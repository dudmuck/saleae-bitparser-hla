class ModelTests(unittest.TestCase):
    def args(self, **changes):
        from test_dslcap_backend import arguments
        return arguments(**changes)

    def test_mode_query_once_and_forwarding(self):
        args = self.args(_dsl_mode_profiles=None, dslcap='custom dslcap', dsl_model='u3pro16', samplerate='500M')
        ports = [hla.parse_spi_port('0,1,2,3')]
        with mock.patch.object(hla.subprocess, 'run', return_value=SimpleNamespace(stdout=json.dumps(RECORDED))) as query:
            hla.validate_backend_args(args, ports)
            cmd = hla.build_dslcap_cmd(args, ports)
        self.assertEqual(query.call_count, 1)
        self.assertEqual(query.call_args.args[0], ['custom dslcap', '--list-modes'])
        self.assertEqual(cmd[cmd.index('--model') + 1], 'u3pro16')
        self.assertNotIn('--model', hla.build_dslcap_cmd(self.args(), ports))

    def test_profiles_rates_counts_lanes_and_phase3(self):
        # Share channel roles to exercise three-lane modes through SPI's API.
        three = [hla.parse_spi_port('0,2,2,5')]
        four = [hla.parse_spi_port('0,1,2,3')]
        hla.build_dslcap_cmd(self.args(samplerate='1G', dsl_model='u3pro16'), three)
        for args, ports in [(self.args(samplerate='1G'), four),
                            (self.args(samplerate='1G'), [hla.parse_spi_port('0,2,2,8')]),
                            (self.args(samplerate='125M', dsl_model='plus'), four),
                            (self.args(dsl_model='u3pro16', dsl_mode='buffer'), four)]:
            with self.subTest(args=args), self.assertRaises(SystemExit):
                hla.build_dslcap_cmd(args, ports)
        # USB high U3 accepts 500k, super alone does not; auto is a union.
        hla.build_dslcap_cmd(self.args(samplerate='500K', dsl_model='u3pro16'), four)
        with self.assertRaises(SystemExit):
            hla.build_dslcap_cmd(self.args(samplerate='500K', dsl_model='u3pro16',
                                         _dsl_mode_profiles=RECORDED['profiles'][-1:]), four)
        hla.build_dslcap_cmd(self.args(samplerate='250M'), four)

    def test_query_failure_and_bad_schema(self):
        from test_dslcap_backend import PORTS
        for result in ('{}', '{', '{"schema":1,"profiles":[{}]}', '[]'):
            with mock.patch.object(hla.subprocess, 'run', return_value=SimpleNamespace(stdout=result)), \
                 self.assertRaisesRegex(SystemExit, 'Cannot read dslcap'):
                hla.build_dslcap_cmd(self.args(_dsl_mode_profiles=None), PORTS)
        with mock.patch.object(hla.subprocess, 'run', side_effect=OSError('missing')), \
             self.assertRaisesRegex(SystemExit, 'Cannot read dslcap'):
            hla.build_dslcap_cmd(self.args(_dsl_mode_profiles=None), PORTS)

    def test_raw_provenance_under_stderr_pressure(self):
        from test_dslcap_backend import PORTS
        with tempfile.TemporaryDirectory() as tmp:
            producer = Path(tmp) / 'producer.py'
            producer.write_text('import sys\n'
                'sys.stderr.write("log\\n" * 50000)\n'
                'sys.stderr.write("dslcap: selected 2a0e:002a DSLogic U3Pro16 speed=super\\n")\n'
                'sys.stdout.buffer.write(b"META samplerate: 1000000\\n" + b"\\x08" * 76)\n')
            raw = Path(tmp) / 'data.raw'
            with mock.patch.object(hla, 'build_dslcap_cmd', return_value=[sys.executable, str(producer)]), \
                 contextlib.redirect_stderr(io.StringIO()):
                hla.run_dslcap_raw_out(self.args(raw_out=str(raw)), PORTS)
            record = json.loads(Path(str(raw) + '.json').read_text())
            self.assertEqual((record['model'], record['usb_speed']), ('DSLogic U3Pro16', 'super'))
            self.assertEqual(record['exit'], 0)
            # Replay reads both new and old records without querying a producer.
            for old in (False, True):
                if old:
                    record.pop('model'); record.pop('usb_speed')
                    Path(str(raw) + '.json').write_text(json.dumps(record))
                with mock.patch.object(hla.subprocess, 'run', side_effect=AssertionError('replay queried dslcap')):
                    args = self.args(input_file=str(raw), samples=None, _dsl_mode_profiles=None)
                    hla.validate_backend_args(args, PORTS)
                    self.assertEqual(hla.dslcap_replay_layout(args, PORTS), (1, 1))

